"""conftest.py — сессионные и общие фикстуры (ШАБЛОН — адаптируйте под проект).

Правила scope:
  scope='session'  — дорогая разовая подготовка: первичная авторизация,
                     создание тестового окружения. Тестовые данные здесь
                     создавать НЕЛЬЗЯ.
  scope='function' — все тестовые данные: создаются в setup, удаляются
                     в teardown через yield.

Правило передачи данных:
  Фикстура ВОЗВРАЩАЕТ значение (yield resource_id), тест принимает его
  параметром. Общих словарей для передачи данных между тестами нет — каждый
  тест независим и может выполняться в любом порядке и параллельно
  (pytest-xdist). app_data — только для действительно сессионного
  (данные окружения, креды).

При форке:
  1. Настройте авторизацию под свой проект (src/example_auth.py — образец).
  2. Выберите имена ролей для access_folder ("admin", "user", ...).
  3. Доменные фикстуры (создание/удаление ресурсов) кладите в conftest.py
     соответствующей директории тестов — образец в
     Tests/Regression_tests/example_resource/conftest.py.
"""

