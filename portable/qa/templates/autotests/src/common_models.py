"""common_models.py — общие pydantic-модели ответов, повторяющиеся как
конвенция самого API (а не специфика отдельного ресурса).

ВАЖНОЕ ИСКЛЮЧЕНИЕ из правила «доменные пакеты самодостаточны»: этот модуль
домены ИМПОРТИРУЮТ, а не копируют. Всё, что описывает конвенцию всего API
(форма ответа create, конверт пагинации, пара токенов), живёт здесь в
одном экземпляре; специфичные схемы ресурса — в models.py его домена.

Формы ниже — стартовые заготовки под типовые конвенции. Форк правит их
под свой реальный API (это НЕ example_*-файл, его можно и нужно менять)
и дописывает сюда свои общие формы, когда одна и та же схема начинает
повторяться в нескольких доменах.
"""

from typing import Generic, List, Optional, TypeVar

from pydantic import BaseModel

T = TypeVar("T")


class ResponseId(BaseModel):
    """Типовой ответ create-эндпоинта: `{"id": ...}`.

    Если ваш API возвращает id иначе (строка/UUID, другое имя поля,
    вложенность) — поправьте здесь, а домены с особой формой ответа
    create описывают её в своих models.py.
    """

    id: int


class PageResult(BaseModel, Generic[T]):
    """Типовой конверт постраничного списка: `{"data": [...], "total": N}`.

    Используйте с конкретным типом элемента: `PageResult[ProjectDto]`.
    Имена полей конверта — ЗАЩИТНАЯ ДОГАДКА (см. docs/api-layer.md,
    Шаг 0.4): сверьте с реальным конвертом вашего API и поправьте.
    """

    data: Optional[List[T]] = None
    total: Optional[int] = None


class TokensPair(BaseModel):
    """Типовая пара токенов ответа логина/refresh (Bearer JWT)."""

    accessToken: Optional[str] = None
    refreshToken: Optional[str] = None
